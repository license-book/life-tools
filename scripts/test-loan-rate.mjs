import { chromium } from "playwright";
const baseUrl = process.env.BASE_URL || "http://127.0.0.1:3000";
const normalize = (text) => (text || "").replace(/\s+/g, " ").trim();
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
await page.goto(baseUrl + "/tools/loan-calculator", { waitUntil: "networkidle", timeout: 30000 });
const payment = page.locator('[data-testid="loan-first-payment"]');
const rateOutput = page.locator('[data-testid="loan-applied-rate"]');
const summaryStats = page.locator('.print-summary .stat');
const before = normalize(await payment.innerText());
if (!before.includes("1,467,052")) throw new Error(`Unexpected 4.2% initial payment: ${before}`);
await page.locator("#rate").fill("5.2");
await page.locator("#rate").blur();
const beforeClick = normalize(await payment.innerText());
if (beforeClick !== before) throw new Error(`Result changed before click: ${beforeClick}`);
await page.getByRole("button", { name: "대출 상환액 계산하기" }).click();
await page.waitForFunction(() => document.querySelector('[data-testid="loan-applied-rate"]')?.textContent?.includes('5.2'), null, { timeout: 3000 });
await page.waitForTimeout(300);
const after = normalize(await payment.innerText());
const applied = normalize(await rateOutput.innerText());
const stats = await summaryStats.allInnerTexts();
const firstRow = normalize(await page.locator('.screen-schedule tbody tr').first().innerText());
console.log(`4.2%: ${before}`);
console.log(`5.2%: ${after}`);
console.log(`Applied: ${applied}`);
console.log(`Stats: ${stats.map(normalize).join(' | ')}`);
console.log(`First row: ${firstRow}`);
if (!after.includes("1,647,333")) throw new Error(`Expected 1,647,333원 at 5.2%, got ${after}`);
if (!applied.includes("5.2")) throw new Error(`Expected applied rate 5.2%, got ${applied}`);
if (after === before) throw new Error("Monthly payment did not change after rate update");
await browser.close();
